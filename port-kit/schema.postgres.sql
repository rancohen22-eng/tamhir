-- =============================================================================
-- Arkia / Teltos flight-booking system — PostgreSQL schema (port from Oracle)
-- Target: self-hosted PostgreSQL 14+ (internal server). No Oracle, no ORDS.
-- Run once: psql -f schema.postgres.sql
-- =============================================================================

-- ── lookups ──────────────────────────────────────────────────────────────────
CREATE TABLE departments (
  dept_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_code  VARCHAR(30)  NOT NULL UNIQUE,
  name_he    VARCHAR(120) NOT NULL,
  name_en    VARCHAR(120),
  is_active  CHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y','N')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE roles (
  role_code VARCHAR(20) PRIMARY KEY,   -- ADMIN / INITIATOR / APPROVER / AGENT / FINANCE
  name_he   VARCHAR(80) NOT NULL,
  name_en   VARCHAR(80) NOT NULL
);

CREATE TABLE currencies (
  code       VARCHAR(3) PRIMARY KEY,
  name_he    VARCHAR(60) NOT NULL,
  name_en    VARCHAR(60) NOT NULL,
  symbol     VARCHAR(6),
  is_default CHAR(1) NOT NULL DEFAULT 'N' CHECK (is_default IN ('Y','N'))
);

CREATE TABLE statuses (
  status_code VARCHAR(30) PRIMARY KEY,
  label_he    VARCHAR(80) NOT NULL,
  label_en    VARCHAR(80) NOT NULL,
  sort_order  INT  NOT NULL DEFAULT 0,
  is_terminal CHAR(1) NOT NULL DEFAULT 'N' CHECK (is_terminal IN ('Y','N'))
);

CREATE TABLE wet_operators (
  operator_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_he     VARCHAR(80) NOT NULL,
  name_en     VARCHAR(80),
  is_active   CHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y','N'))
);

CREATE TABLE airports (
  iata      VARCHAR(4) PRIMARY KEY,
  name_he   VARCHAR(200),
  name_en   VARCHAR(200),
  city_he   VARCHAR(200),
  city_en   VARCHAR(200),
  country   VARCHAR(100),
  is_active CHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y','N'))
);

-- ── users & roles ────────────────────────────────────────────────────────────
CREATE TABLE app_users (
  user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(60)  NOT NULL UNIQUE,
  full_name     VARCHAR(150) NOT NULL,
  email         VARCHAR(200) NOT NULL,
  dept_id       BIGINT REFERENCES departments(dept_id),
  pref_lang     VARCHAR(2) NOT NULL DEFAULT 'HE' CHECK (pref_lang IN ('HE','EN')),
  is_active     CHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y','N')),
  notify_email  CHAR(1) NOT NULL DEFAULT 'Y' CHECK (notify_email IN ('Y','N')),
  password_hash VARCHAR(200),   -- use bcrypt/argon2 in the app layer (see ENDPOINTS.md)
  password_salt VARCHAR(60),    -- bcrypt embeds salt in hash → salt may be unused
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_roles (
  user_id   BIGINT NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,
  role_code VARCHAR(20) NOT NULL REFERENCES roles(role_code),
  PRIMARY KEY (user_id, role_code)
);

-- multiple approvers per department supported (composite PK)
CREATE TABLE dept_approvers (
  dept_id          BIGINT NOT NULL REFERENCES departments(dept_id) ON DELETE CASCADE,
  approver_user_id BIGINT NOT NULL REFERENCES app_users(user_id),
  PRIMARY KEY (dept_id, approver_user_id)
);

CREATE TABLE agents (
  agent_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL UNIQUE REFERENCES app_users(user_id),
  agency_name   VARCHAR(150) NOT NULL,
  contact_email VARCHAR(200),
  contact_phone VARCHAR(40),
  logo_blob     BYTEA,
  logo_mime     VARCHAR(100),
  is_active     CHAR(1) NOT NULL DEFAULT 'Y' CHECK (is_active IN ('Y','N'))
);

-- ── core: bookings ───────────────────────────────────────────────────────────
CREATE TABLE bookings (
  booking_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_id             BIGINT NOT NULL REFERENCES departments(dept_id),
  initiator_id        BIGINT NOT NULL REFERENCES app_users(user_id),
  agent_id            BIGINT REFERENCES agents(agent_id),
  approver_id         BIGINT REFERENCES app_users(user_id),
  status              VARCHAR(30) NOT NULL DEFAULT 'NEW' REFERENCES statuses(status_code),
  open_date           DATE NOT NULL DEFAULT CURRENT_DATE,
  departure_date      DATE,
  ticketing_date      DATE,
  price               NUMERIC(14,2) CHECK (price IS NULL OR price >= 0),
  currency_code       VARCHAR(3) NOT NULL DEFAULT 'USD' REFERENCES currencies(code),
  pnr                 VARCHAR(20),
  unique_booking_ref  VARCHAR(60) UNIQUE,
  pax_count           INT DEFAULT 1,
  pref_time           VARCHAR(20),
  wet_operator_id     BIGINT,                 -- soft ref to wet_operators
  origin_iata         VARCHAR(4),
  dest_iata           VARCHAR(4),
  low_cost            CHAR(1) DEFAULT 'N',    -- agent marks LOW COST at quote
  urgent              CHAR(1) DEFAULT 'N',    -- agent-initiated urgent quote
  quote_notes         VARCHAR(2000),
  trip_details        TEXT,
  rejection_reason    VARCHAR(1000),
  cancel_reason       VARCHAR(1000),
  cancel_requested_by BIGINT REFERENCES app_users(user_id),
  cancel_requested_at TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX bookings_dept_ix      ON bookings(dept_id);
CREATE INDEX bookings_status_ix    ON bookings(status);
CREATE INDEX bookings_agent_ix     ON bookings(agent_id);
CREATE INDEX bookings_initiator_ix ON bookings(initiator_id);

-- ── attachments (bytea in DB; or swap to a file store/S3-compatible later) ─────
CREATE TABLE booking_files (
  file_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id  BIGINT NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
  file_kind   VARCHAR(30) NOT NULL CHECK (file_kind IN ('QUOTE_SCREENSHOT','FINAL_TICKET','OTHER')),
  filename    VARCHAR(300) NOT NULL,
  mime_type   VARCHAR(150),
  file_blob   BYTEA NOT NULL,
  uploaded_by BIGINT NOT NULL REFERENCES app_users(user_id),
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX booking_files_booking_ix ON booking_files(booking_id);

-- ── audit timeline (who did what, when) ───────────────────────────────────────
CREATE TABLE booking_status_log (
  log_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id  BIGINT NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
  from_status VARCHAR(30),
  to_status   VARCHAR(30) NOT NULL,
  action_by   BIGINT NOT NULL REFERENCES app_users(user_id),
  action_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  note        VARCHAR(2000)
);
CREATE INDEX bsl_booking_ix ON booking_status_log(booking_id, action_at);

-- ── in-app bell notifications ─────────────────────────────────────────────────
CREATE TABLE notifications (
  notif_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,
  booking_id BIGINT REFERENCES bookings(booking_id) ON DELETE CASCADE,
  notif_type VARCHAR(40),
  message    VARCHAR(1000) NOT NULL,
  is_read    CHAR(1) NOT NULL DEFAULT 'N' CHECK (is_read IN ('Y','N')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX notif_user_unread_ix ON notifications(user_id, is_read);

-- ── bilingual notification templates (status × recipient role) ────────────────
CREATE TABLE notif_templates (
  status_code    VARCHAR(30) NOT NULL REFERENCES statuses(status_code),
  recipient_role VARCHAR(20) NOT NULL,   -- AGENT / INITIATOR / APPROVER
  subject_he     VARCHAR(200) NOT NULL,
  subject_en     VARCHAR(200) NOT NULL,
  msg_he         VARCHAR(1000) NOT NULL,
  msg_en         VARCHAR(1000) NOT NULL,
  PRIMARY KEY (status_code, recipient_role)
);

CREATE TABLE report_templates (
  template_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(150) NOT NULL,
  owner_id     BIGINT NOT NULL REFERENCES app_users(user_id),
  columns_json JSONB,
  filters_json JSONB,
  is_shared    CHAR(1) NOT NULL DEFAULT 'N' CHECK (is_shared IN ('Y','N')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── sessions / security / email tracking (were runtime migrations in Oracle) ──
CREATE TABLE api_sessions (
  token      VARCHAR(64) PRIMARY KEY,   -- random 128-bit hex; app generates
  user_id    BIGINT NOT NULL REFERENCES app_users(user_id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL       -- now() + 30 days
);

CREATE TABLE login_log (
  log_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id  BIGINT,
  username VARCHAR(60),
  login_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE login_attempts (
  attempt_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     VARCHAR(60),
  ip           VARCHAR(60),
  success      CHAR(1) NOT NULL DEFAULT 'N' CHECK (success IN ('Y','N')),
  attempted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX login_attempts_ix ON login_attempts(username, attempted_at);

-- one-time tokens for approve-from-email (agent/approver act without login)
CREATE TABLE booking_action_tokens (
  token      VARCHAR(70) PRIMARY KEY,
  booking_id BIGINT NOT NULL,
  action     VARCHAR(20) NOT NULL,   -- 'approve'
  user_id    BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ,            -- now() + 7 days
  used       CHAR(1) NOT NULL DEFAULT 'N' CHECK (used IN ('Y','N'))
);

-- sent-email log + read tracking (1x1 pixel)
CREATE TABLE email_log (
  log_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token      VARCHAR(70) UNIQUE,     -- pixel token
  booking_id BIGINT,
  recipient  VARCHAR(200),
  user_id    BIGINT,
  kind       VARCHAR(60),           -- AGENT_REQUEST / APPROVER_QUOTE / WELCOME / RESET / STATUS:<code>
  subject    VARCHAR(300),
  sent_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  opened     CHAR(1) NOT NULL DEFAULT 'N' CHECK (opened IN ('Y','N')),
  opened_at  TIMESTAMPTZ,
  open_count INT DEFAULT 0
);
